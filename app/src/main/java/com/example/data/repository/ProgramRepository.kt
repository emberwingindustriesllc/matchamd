    fun searchPrograms(
        query: String = "",
        specialty: MedicalSpecialty? = null,
        visaSponsorship: VisaSponsorship? = null,
        minStepScore: Int? = null,
        programType: ProgramType? = null
    ): List<ResidencyProgram> {
        return verifiedPrograms.filter { p ->
            val matchesQuery = query.isBlank() ||
                    p.name.contains(query, ignoreCase = true) ||
                    p.hospitalName.contains(query, ignoreCase = true) ||
                    p.city.contains(query, ignoreCase = true) ||
                    p.state.contains(query, ignoreCase = true) ||
                    p.subspecialtyFocus.contains(query, ignoreCase = true) ||
                    p.programType.displayName.contains(query, ignoreCase = true)

            val matchesSpec = specialty == null || p.specialty == specialty

            val matchesVisa = visaSponsorship == null || when (visaSponsorship) {
                VisaSponsorship.J1_AND_H1B -> p.visaSponsorship == VisaSponsorship.J1_AND_H1B
                VisaSponsorship.J1_ONLY -> p.visaSponsorship == VisaSponsorship.J1_ONLY || p.visaSponsorship == VisaSponsorship.J1_AND_H1B
                VisaSponsorship.NO_VISA -> true
            }

            val matchesScore = minStepScore == null || minStepScore <= 0 || p.minStep2Score <= minStepScore

            val matchesType = programType == null || p.programType == programType

            matchesQuery && matchesSpec && matchesVisa && matchesScore && matchesType
        }
    }
